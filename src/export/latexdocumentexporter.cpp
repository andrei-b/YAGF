ExportResult LatexDocumentExporter::write(const core::OcrDocument &document,const QString &destination,
                                         const std::atomic_bool &cancelled,const ExportProgress &progress)
{
    if (cancelled.load()) return {.status=ExportResult::Status::Cancelled};
    QSaveFile file(destination); if (!file.open(QIODevice::WriteOnly)) return failure(file.errorString());
    QTemporaryDir render;
    QDir parent(QFileInfo(destination).absolutePath());
    QTemporaryDir assets(parent.filePath(".yagf-latex-XXXXXX"));
    if (!render.isValid() || !assets.isValid()) return failure(QStringLiteral("Could not prepare LaTeX export files."));
    const auto assetName="yagf-assets-"+QUuid::createUuid().toString(QUuid::WithoutBraces);
    bool hasAssets=false;
    QTextStream out(&file); out<<preamble;
    QSet<char32_t> unicode;
    for (const auto &page:document.pages) for (const auto &word:page.words)
        for (auto value:(core::formulaSourceText(word)+word.text).toUcs4()) if (!core::latexForUnicode(value).isEmpty()) unicode.insert(value);
    out<<"\\ifPDFTeX\n";
    for (auto value:unicode) out<<"\\DeclareUnicodeCharacter{"<<QString::number(value,16).toUpper()<<"}{\\ensuremath{"<<core::latexForUnicode(value)<<"}}\n";
    out<<"\\fi\n\\begin{document}\n";
    for (int n=0;n<document.pages.size();++n) {
        if (cancelled.load()) return {.status=ExportResult::Status::Cancelled};
        const auto &page=document.pages[n];
        if (n) out<<"\\clearpage\n";
        out<<"% Source page "<<page.number<<'\n';
        QHash<QString,const core::OcrWord *> words;
        for (const auto &word:page.words) words.insert(word.id,&word);
        QImage image;
        QSet<QString> emitted;
        const auto formattedWord=[&](const core::OcrWord &word,bool heading=false)->std::expected<QString,QString> {
            auto text=passage(core::formulaSourceText(word),heading); if (!text) return text;
            if (word.bold) *text="{\\bfseries "+*text+'}';
            if (word.italic) *text="{\\itshape "+*text+'}';
            return text;
        };
        const auto regions = exportRegions(page);
        for (int index=0;index<regions.size();++index) {
            if (cancelled.load()) return {.status=ExportResult::Status::Cancelled};
            const auto &region=regions[index]; const auto source=regionSource(region,words);
            const auto fail=[&](const QString &e) { return failure(QStringLiteral("Page %1, region %2: %3").arg(page.number).arg(index+1).arg(e)); };
            for (const auto &paragraph:region.paragraphs) for (const auto &line:paragraph.lines) for (const auto &id:line.wordIds) emitted.insert(id);
            if (region.isFigure()) {
                if (image.isNull()) { auto read=readExportPage(document,page.number,render,cancelled); if (!read) return read.error(); image=std::move(*read); }
                if (region.bounds.isEmpty() || !image.rect().contains(region.bounds)) return fail("Figure lies outside its source page.");
                const auto png=QString("page-%1-figure-%2.png").arg(page.number).arg(index+1);
                if (!image.copy(region.bounds).save(QDir(assets.path()).filePath(png),"PNG")) return fail("Could not save figure image.");
                hasAssets=true;
                const double width=std::clamp(double(region.bounds.width())/page.width,.05,1.);
                out<<"\\begin{center}\n\\includegraphics[width="<<QString::number(width,'f',4)<<"\\linewidth,height=.75\\textheight,keepaspectratio]{"<<assetName<<'/'<<png<<"}\n\\end{center}\n";
            } else if (region.type=="equation" || region.type=="formula") {
                if (source.trimmed().isEmpty()) continue;
                auto body=equation(source); if (!body) return fail(body.error()); out<<*body;
            } else if (region.type=="table") {
                auto body=table(source,region.tableLayout); if (!body) return fail(body.error()); out<<*body;
            } else if (region.type=="code") {
                // Escape code as prose: raw verbatim end markers from OCR must
                // never terminate an environment and become executable TeX.
                out<<"{\\ttfamily\\obeylines\n"<<prose(source)<<"\n}\n";
            } else {
                const bool heading=region.type=="heading" || region.type=="sectionheader";
                QStringList paragraphs;
                for (const auto &paragraph:region.paragraphs) {
                    QStringList lines;
                    for (const auto &line:paragraph.lines) {
                        QStringList tokens;
                        for (const auto &id:line.wordIds) if (const auto *word=words.value(id)) {
                            auto token=formattedWord(*word,heading); if (!token) return fail(token.error()); tokens.append(*token);
                        }
                        lines.append(tokens.join(' '));
                    }
                    paragraphs.append(lines.join('\n'));
                }
                const auto text=paragraphs.join("\n\n");
                if (heading) out<<"\\section*{"<<text<<"}\n";
                else out<<text<<"\n\n";
            }
        }
        for (const auto &word:page.words) if (!emitted.contains(word.id)) {
            auto text=formattedWord(word); if (!text) return failure(text.error()); out<<*text<<"\n\n";
        }
        if (progress) progress(n+1,document.pages.size());
    }
    out<<"\\end{document}\n"; out.flush();
    if (cancelled.load()) return {.status=ExportResult::Status::Cancelled};
    if (out.status()!=QTextStream::Ok) return failure(QStringLiteral("Could not write LaTeX document."));
    if (hasAssets) {
        if (!parent.rename(QFileInfo(assets.path()).fileName(),assetName)) return failure(QStringLiteral("Could not publish LaTeX figure assets."));
        assets.setAutoRemove(false);
    }
    if (cancelled.load() || !file.commit()) {
        if (hasAssets) QDir(parent.filePath(assetName)).removeRecursively();
        return cancelled.load() ? ExportResult{.status=ExportResult::Status::Cancelled} : failure(file.errorString());
    }
    return {.status=ExportResult::Status::Success};
}
