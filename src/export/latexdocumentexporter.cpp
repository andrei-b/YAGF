ExportResult failure(const QString &error) { return {.status=ExportResult::Status::Error,.error=error}; }
QString prose(const QString &text)
{
    QString out;
    for (const auto c:text) {
        if (c=='\\') out+="\\textbackslash{}";
        else if (c=='^') out+="\\textasciicircum{}";
        else if (c=='~') out+="\\textasciitilde{}";
        else if (QStringLiteral("#$%&_{}").contains(c)) out+='\\'+QString(c);
        else if (c=='\n') out+="\n\n";
        else if (c.isPrint() || c.isSpace()) out+=c;
    }
    return out;
}
std::expected<QString,QString> passage(const QString &text,bool inlineOnly=false)
{
    QString out; qsizetype at=0;
    for (const auto &span:core::mathTextSpans(text)) {
        out+=prose(text.mid(at,span.start-at));
        const auto safe=detail::safeLatexMath(span.source,true);
        if (!safe) return std::unexpected(safe.error());
        const bool display=span.display && !inlineOnly;
        out+=(display?"\\[":"\\(")+*safe+(display?"\\]":"\\)"); at=span.start+span.length;
    }
    return out+prose(text.mid(at));
}
QString regionSource(const core::OcrRegion &region,const QHash<QString,const core::OcrWord *> &words)
{
    QStringList paragraphs;
    for (const auto &paragraph:region.paragraphs) {
        QStringList lines;
        for (const auto &line:paragraph.lines) {
            QStringList tokens; for (const auto &id:line.wordIds) if (const auto *word=words.value(id)) tokens.append(core::formulaSourceText(*word));
            lines.append(tokens.join(' '));
        }
        paragraphs.append(lines.join('\n'));
    }
    return paragraphs.join("\n\n");
}
std::expected<QString,QString> equation(QString source)
{
    const auto spans=core::mathTextSpans(source);
    for (auto it=spans.crbegin();it!=spans.crend();++it) source.replace(it->start,it->length,it->source);
    auto safe=detail::safeLatexMath(source.trimmed(),true);
    if (!safe) return std::unexpected(safe.error());
    return "\\[\n"+*safe+"\n\\]\n";
}
std::expected<QString,QString> table(const QString &source,const QJsonArray &layout)
{
    const auto rows=source.split('\n',Qt::SkipEmptyParts);
    int columns=1; QVector<int> occupied(64,0); QStringList outputRows;
    if (rows.size()>4096) return std::unexpected(QStringLiteral("Table is too large for LaTeX export."));
    for (int i=0;i<rows.size();++i) {
        const auto cells=rows[i].split('\t'); const auto formats=i<layout.size()?layout[i].toArray():QJsonArray{}; QStringList rendered;
        int column=0;
        for (int j=0;j<cells.size();++j) {
            auto cell=passage(cells[j],true); if (!cell) return std::unexpected(cell.error());
            const auto format=j<formats.size()?formats[j].toObject():QJsonObject{};
            if (format["header"].toBool()) *cell="\\textbf{"+*cell+'}';
            const int rowSpan=std::max(1,format["rowspan"].toInt(1)), colSpan=std::max(1,format["colspan"].toInt(1));
            while (column<64 && occupied[column]>i) { rendered.append(QString()); ++column; }
            if (column+colSpan>64 || rowSpan>4096) return std::unexpected(QStringLiteral("Table spans exceed the export limit."));
            for (int at=column;at<column+colSpan;++at) occupied[at]=i+rowSpan;
            column+=colSpan;
            if (rowSpan>1) *cell="\\multirow{"+QString::number(rowSpan)+"}{*}{"+*cell+'}';
            if (colSpan>1) *cell="\\multicolumn{"+QString::number(colSpan)+"}{l}{"+*cell+'}';
            rendered.append(*cell);
        }
        outputRows.append(rendered.join(" & ")+" \\\\\n");
        columns=std::max(columns,column);
    }
    return "\\begin{longtable}{"+QString(columns,'l')+"}\n"+outputRows.join(QString())+"\\end{longtable}\n";
}
